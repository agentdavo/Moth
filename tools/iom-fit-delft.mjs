// Fit an independent residuary-resistance model to the Delft Systematic Yacht Hull Series data
// (Gerritsma, Onnink & Versluis 1981; 22 hulls, 308 runs; UCI "Yacht Hydrodynamics" data set,
// https://archive.ics.uci.edu/dataset/243/yacht+hydrodynamics, CC BY 4.0; copy in docs/results/iom/).
// Model per Froude number:  ln(1000 Rr/W) = c0 + c1 ln(LVR) + c2 Cp + c3 ln(BTR) + c4 LCB
// The Delft series 1 covers LVR 4.34–5.14 only; the IOM (LVR ~6.4) needs extrapolation along c1,
// so this model is used as the *alternative* hull model in the sensitivity study, not the default.
// usage: node tools/iom-fit-delft.mjs  -> src/iom/physics/delftFit.js + docs/results/iom/delft-fit.json
import fs from 'node:fs';
import { solveSmall } from '../src/physics/linalg.js';
import { orcRr } from '../src/iom/physics/resistance.js';

const rows = fs.readFileSync('docs/results/iom/delft-yacht-hydrodynamics.data', 'utf8').trim().split(/\n/)
  .map((l) => l.trim().split(/\s+/).map(Number)).filter((r) => r.length === 7 && r.every(Number.isFinite));
// columns: LCB (% of L from midship, - aft), Cp, L/V^(1/3), B/T, L/B, Fn, Rr/W*1000
const fns = [...new Set(rows.map((r) => r[5]))].sort((a, b) => a - b);
const fits = [];
for (const fn of fns) {
  const R = rows.filter((r) => r[5] === fn && r[6] > 0);
  const X = R.map((r) => [1, Math.log(r[2]), r[1], Math.log(r[3]), r[0]]);
  const y = R.map((r) => Math.log(r[6]));
  const n = 5, A = Array.from({ length: n }, () => new Array(n).fill(0)), b = new Array(n).fill(0);
  X.forEach((x, k) => { for (let i = 0; i < n; i++) { b[i] += x[i] * y[k]; for (let j = 0; j < n; j++) A[i][j] += x[i] * x[j]; } });
  for (let i = 1; i < n; i++) A[i][i] += 1e-6; // ridge for conditioning
  const c = solveSmall(A, b);
  const res = X.map((x, k) => x.reduce((s, xi, i) => s + xi * c[i], 0) - y[k]);
  const rms = Math.sqrt(res.reduce((s, e) => s + e * e, 0) / res.length);
  fits.push({ fn, c: c.map((v) => +v.toFixed(5)), rmsLog: +rms.toFixed(4), n: R.length });
}
const header = `// Generated by tools/iom-fit-delft.mjs from the Delft Series 1 data (Gerritsma et al. 1981, UCI 243).
// ln(1000 Rr/W) = c0 + c1 ln(LVR) + c2 Cp + c3 ln(BTR) + c4 LCB(% L from midship, - aft)
// Valid data range: LVR 4.34–5.14, BTR 2.81–5.35, Cp 0.53–0.60, Fn 0.125–0.45. Extrapolated for the IOM.
`;
fs.writeFileSync('src/iom/physics/delftFit.js', `${header}export const DELFT_FIT = ${JSON.stringify(fits.map((f) => ({ fn: f.fn, c: f.c })))};\n`);
fs.writeFileSync('docs/results/iom/delft-fit.json', JSON.stringify({ model: 'ln(1000Rr/W)=c0+c1 ln LVR+c2 Cp+c3 ln BTR+c4 LCB', fits }, null, 1));
console.log('Fn    c1(lnLVR)  rms(log)  n');
for (const f of fits) console.log(f.fn.toFixed(3), f.c[1].toFixed(2).padStart(8), f.rmsLog.toFixed(3).padStart(8), f.n);
// compare with ORC inside the overlap (LVR 4.8, BTR 3.8, Cp 0.56, LCB -2.3)
console.log('\nOverlap check vs ORC surfaces (LVR 4.8, BTR 3.8):  Fn  Delft-fit  ORC');
for (const f of fits) {
  const v = Math.exp(f.c[0] + f.c[1] * Math.log(4.8) + f.c[2] * 0.56 + f.c[3] * Math.log(3.8) + f.c[4] * -2.3);
  console.log(f.fn.toFixed(3), v.toFixed(3).padStart(9), orcRr(f.fn, 4.8, 3.8).toFixed(3).padStart(8));
}
console.log('\nIOM extrapolation (LVR 6.4, BTR 3.3, Cp 0.56, LCB -3.5):  Fn  Delft-fit  ORC');
for (const f of fits) {
  const v = Math.exp(f.c[0] + f.c[1] * Math.log(6.4) + f.c[2] * 0.56 + f.c[3] * Math.log(3.3) + f.c[4] * -3.5);
  console.log(f.fn.toFixed(3), v.toFixed(3).padStart(9), orcRr(f.fn, 6.4, 3.3).toFixed(3).padStart(8));
}
