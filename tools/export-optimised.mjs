// Copies the optimised designs from docs/results into src/physics/optimised.js for the app presets.
import fs from 'node:fs';
const out = {};
for (const t of ['light', 'medium', 'strong']) {
  const f = `docs/results/opt-${t}.json`;
  if (!fs.existsSync(f)) continue;
  const r = JSON.parse(fs.readFileSync(f));
  const d = r.design;
  d.name = `Optimised ${t}`;
  const round = (o) => { for (const k of Object.keys(o)) { if (typeof o[k] === 'number') o[k] = +o[k].toPrecision(4); else if (o[k] && typeof o[k] === 'object') round(o[k]); } };
  round(d);
  out[t] = d;
}
fs.writeFileSync('src/physics/optimised.js', `// Generated by tools/export-optimised.mjs from docs/results/opt-*.json (CMA-ES studies).\nexport const OPTIMISED = ${JSON.stringify(out, null, 1)};\n`);
console.log('exported', Object.keys(out));
